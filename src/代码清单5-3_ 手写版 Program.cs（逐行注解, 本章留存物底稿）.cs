// 第 1 行: 收集启动原料——命令行参数与默认配置由建造者读齐, 这个类型第 6 章正式认识, 此处眼熟即可
var builder = WebApplication.CreateBuilder(args);

// 第 2 行: 建造完工——得到应用实例 app, 之后每一行都是在往它身上登记功能
var app = builder.Build();

// 第 3 行: 登记一条地址约定——有人 GET 访问根路径 /, 就执行箭头后的小函数, 返回的字符串作为响应正文
app.MapGet("/", () => "这是来自 FirstWebApp 的问候: 你的第一个 ASP.NET Core 应用正在运行。");

// 第 4 行: 兜底——前面没有地址认领的请求统一落到这里, 返回 404 与一句指引,
// 让「不存在的路径」也得到体面的答复, 而不是框架默认的干巴巴状态行
app.MapFallback(() => Results.NotFound("你访问的路径不存在, 先试试根路径 / 。"));

// 第 5 行: 启动监听——执行后程序停在这一行等请求上门, 不会往下走也不会返回
app.Run();